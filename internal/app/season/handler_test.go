func TestCreateSeason_Errors(t *testing.T) {
	withField := func(field, value string) string {
		var m map[string]json.RawMessage
		if err := json.Unmarshal([]byte(validSeasonBody), &m); err != nil {
			panic(err)
		}
		if value == "" {
			delete(m, field)
		} else {
			m[field] = json.RawMessage(value)
		}
		b, _ := json.Marshal(m)
		return string(b)
	}

	tests := []struct {
		name       string
		path       func(l db.League) string
		body       string
		wantStatus int
	}{
		{"invalid JSON", seasonsPath, `{"name":`, http.StatusBadRequest},
		{"missing name", seasonsPath, withField("name", ""), http.StatusUnprocessableEntity},
		{"name too long", seasonsPath, withField("name", `"`+strings.Repeat("a", 51)+`"`), http.StatusUnprocessableEntity},
		{"end before start", seasonsPath, withField("end_on", `"2025-01-01T00:00:00Z"`), http.StatusUnprocessableEntity},
		{"negative points", seasonsPath, withField("match_win_pts", `-1`), http.StatusUnprocessableEntity},
		{"unknown tie breaker", seasonsPath, withField("tie_breakers", `["coin_flip"]`), http.StatusUnprocessableEntity},
		{"same name in the same league", seasonsPath, validSeasonBody, http.StatusConflict},
		{"unknown league", func(db.League) string { return "/api/v1/leagues/" + uuid.NewString() + "/seasons" }, validSeasonBody, http.StatusNotFound},
		{"invalid league id", func(db.League) string { return "/api/v1/leagues/abc/seasons" }, validSeasonBody, http.StatusBadRequest},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			s := testdb.New(t, testPool)
			league := s.CreateLeague(testdb.LeagueParams{})
			s.CreateSeason(testdb.SeasonParams{League: &league, Name: "2025-2026"})

			rec := testhttp.Do(t, newTestRouter(), http.MethodPost, tt.path(league), tt.body)
			if rec.Code != tt.wantStatus {
				t.Errorf("status = %d, want %d, body = %s", rec.Code, tt.wantStatus, rec.Body)
			}
		})
	}
}

