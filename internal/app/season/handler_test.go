func TestRemoveTeam(t *testing.T) {
	s := testdb.New(t, testPool)
	season := s.CreateSeason(testdb.SeasonParams{})
	team := s.CreateTeam(testdb.TeamParams{})
	s.RegisterTeams(season, team)

	rec := testhttp.Do(t, newTestRouter(), http.MethodDelete, seasonTeamPath(season, team), "")
	if rec.Code != http.StatusOK {
		t.Fatalf("status = %d, want %d, body = %s", rec.Code, http.StatusOK, rec.Body)
	}

	var count int
	err := testPool.QueryRow(context.Background(),
		`SELECT count(*) FROM season_team WHERE season_id = $1 AND team_id = $2`, season.ID, team.ID).Scan(&count)
	if err != nil {
		t.Fatalf("count registrations: %v", err)
	}
	if count != 0 {
		t.Errorf("team is still registered after delete")
	}
}

