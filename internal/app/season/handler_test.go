func TestAddTeamThenListTeams(t *testing.T) {
	s := testdb.New(t, testPool)
	season := s.CreateSeason(testdb.SeasonParams{})
	lyon := s.CreateTeam(testdb.TeamParams{Name: "Lyon"})
	lens := s.CreateTeam(testdb.TeamParams{Name: "Lens"})
	s.CreateTeam(testdb.TeamParams{Name: "Nantes"})
	router := newTestRouter()

	for _, team := range []db.Team{lyon, lens} {
		rec := testhttp.Do(t, router, http.MethodPost, seasonTeamPath(season, team), "")
		if rec.Code != http.StatusOK {
			t.Fatalf("add team %q: status = %d, want %d, body = %s", team.Name, rec.Code, http.StatusOK, rec.Body)
		}
	}

	rec := testhttp.Do(t, router, http.MethodGet, seasonPath(season)+"/teams", "")
	if rec.Code != http.StatusOK {
		t.Fatalf("list: status = %d, want %d, body = %s", rec.Code, http.StatusOK, rec.Body)
	}

	var got []struct {
		ID   uuid.UUID `json:"id"`
		Name string    `json:"name"`
	}
	if err := json.NewDecoder(rec.Body).Decode(&got); err != nil {
		t.Fatalf("decode list response: %v, body = %s", err, rec.Body)
	}

	var names []string
	for _, team := range got {
		names = append(names, team.Name)
	}
	if !slices.Equal(names, []string{"Lens", "Lyon"}) {
		t.Errorf("teams = %v, want [Lens Lyon] (registered teams, sorted by name)", names)
	}
}

