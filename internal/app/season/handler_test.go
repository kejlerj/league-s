func newTestRouter() http.Handler {
	r := chi.NewRouter()
	r.Mount("/api/v1/leagues/{leagueID}/seasons", NewHandler(NewPostgresStore(testPool)).Routes())
	return r
}

func seasonsPath(l db.League) string {
	return fmt.Sprintf("/api/v1/leagues/%s/seasons", l.ID)
}

func seasonPath(s db.Season) string {
	return fmt.Sprintf("/api/v1/leagues/%s/seasons/%s", s.LeagueID, s.ID)
}

func seasonTeamPath(s db.Season, t db.Team) string {
	return fmt.Sprintf("%s/teams/%s", seasonPath(s), t.ID)
}

const validSeasonBody = `{
	"name": "2025-2026",
	"start_on": "2025-08-01T00:00:00Z",
	"end_on": "2026-05-31T00:00:00Z",
	"match_win_pts": 3,
	"match_draw_pts": 1,
	"match_loss_pts": 0,
	"tie_breakers": ["goal_difference", "head_to_head"]
}`

func TestCreateThenGetSeason(t *testing.T) {
	league := testdb.New(t, testPool).CreateLeague(testdb.LeagueParams{})
	router := newTestRouter()

	rec := testhttp.Do(t, router, http.MethodPost, seasonsPath(league), validSeasonBody)
	if rec.Code != http.StatusCreated {
		t.Fatalf("create: status = %d, want %d, body = %s", rec.Code, http.StatusCreated, rec.Body)
	}

	var created seasonResponse
	if err := json.NewDecoder(rec.Body).Decode(&created); err != nil {
		t.Fatalf("decode create response: %v", err)
	}
	if created.ID == uuid.Nil {
		t.Fatal("create: id is 0, want the id generated by the database")
	}

	rec = testhttp.Do(t, router, http.MethodGet, fmt.Sprintf("%s/%s", seasonsPath(league), created.ID), "")
	if rec.Code != http.StatusOK {
		t.Fatalf("get: status = %d, want %d, body = %s", rec.Code, http.StatusOK, rec.Body)
	}

	var got seasonResponse
	if err := json.NewDecoder(rec.Body).Decode(&got); err != nil {
		t.Fatalf("decode get response: %v", err)
	}

	wantStart := time.Date(2025, time.August, 1, 0, 0, 0, 0, time.UTC)
	wantEnd := time.Date(2026, time.May, 31, 0, 0, 0, 0, time.UTC)
	switch {
	case got.Name != "2025-2026":
		t.Errorf("name = %q, want %q", got.Name, "2025-2026")
	case !got.StartOn.Equal(wantStart):
		t.Errorf("start_on = %v, want %v", got.StartOn, wantStart)
	case !got.EndOn.Equal(wantEnd):
		t.Errorf("end_on = %v, want %v", got.EndOn, wantEnd)
	case got.MatchWinPts != 3 || got.MatchDrawPts != 1 || got.MatchLossPts != 0:
		t.Errorf("points = %d/%d/%d, want 3/1/0", got.MatchWinPts, got.MatchDrawPts, got.MatchLossPts)
	case !slices.Equal(got.TieBreakers, []string{"goal_difference", "head_to_head"}):
		t.Errorf("tie_breakers = %v, want [goal_difference head_to_head]", got.TieBreakers)
	case got.LeagueID != league.ID:
		t.Errorf("league_id = %s, want %s (from the URL)", got.LeagueID, league.ID)
	}
}

