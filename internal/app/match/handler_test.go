func TestListMatches_Filters(t *testing.T) {
	f := newFixture(t)
	first := f.do(t, http.MethodPost, f.matchesPath(), scheduleBody(f.home.ID, f.away.ID, 1, "2025-10-04T18:00:00Z"), http.StatusCreated)
	second := f.do(t, http.MethodPost, f.matchesPath(), scheduleBody(f.away.ID, f.third.ID, 2, "2025-10-11T18:00:00Z"), http.StatusCreated)
	undated := f.do(t, http.MethodPost, f.matchesPath(), scheduleBody(f.third.ID, f.home.ID, 3, ""), http.StatusCreated)

	tests := []struct {
		name  string
		query string
		want  []uuid.UUID
	}{
		{"everything, by matchday", "", []uuid.UUID{first.ID, second.ID, undated.ID}},
		{"one matchday", "?matchday=2", []uuid.UUID{second.ID}},
		{"one team", "?team=" + f.home.ID.String(), []uuid.UUID{first.ID, undated.ID}},
		{"from a date", "?from=2025-10-11", []uuid.UUID{second.ID}},
		{"until a date, included", "?to=2025-10-04", []uuid.UUID{first.ID}},
		{"between two dates", "?from=2025-10-01&to=2025-10-31", []uuid.UUID{first.ID, second.ID}},
		{"team and matchday", "?matchday=1&team=" + f.third.ID.String(), nil},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			rec := testhttp.Do(t, f.router, http.MethodGet, f.matchesPath()+tt.query, "")
			if rec.Code != http.StatusOK {
				t.Fatalf("status = %d, want %d, body = %s", rec.Code, http.StatusOK, rec.Body)
			}

			matches := decode[[]matchResponse](t, rec)
			got := make([]uuid.UUID, len(matches))
			for i, m := range matches {
				got[i] = m.ID
			}
			if fmt.Sprint(got) != fmt.Sprint(append([]uuid.UUID{}, tt.want...)) {
				t.Errorf("matches = %v, want %v", got, tt.want)
			}
		})
	}

	for _, query := range []string{"?matchday=abc", "?matchday=0", "?from=04/10/2025", "?to=tomorrow", "?team=abc"} {
		if rec := testhttp.Do(t, f.router, http.MethodGet, f.matchesPath()+query, ""); rec.Code != http.StatusBadRequest {
			t.Errorf("%s: status = %d, want %d", query, rec.Code, http.StatusBadRequest)
		}
	}
}
