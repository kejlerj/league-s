func TestScheduleMatch_ConcurrentRequestsKeepOneMatchPerTeamAndMatchday(t *testing.T) {
	f := newFixture(t)
	opponents := []db.Team{f.away, f.third}

	codes := make([]int, len(opponents))
	var wg sync.WaitGroup
	for i, opponent := range opponents {
		wg.Go(func() {
			codes[i] = testhttp.Do(t, f.router, http.MethodPost, f.matchesPath(), scheduleBody(f.home.ID, opponent.ID, 1, "")).Code
		})
	}
	wg.Wait()

	created, refused := 0, 0
	for _, code := range codes {
		switch code {
		case http.StatusCreated:
			created++
		case http.StatusConflict:
			refused++
		}
	}
	if created != 1 || refused != 1 {
		t.Errorf("statuses = %v, want one 201 and one 409", codes)
	}
}

func TestMatch_IsNotReachableFromAnotherLeague(t *testing.T) {
	f := newFixture(t)
	m := f.schedule(t, f.home, f.away, 1)
	other := f.seed.CreateLeague(testdb.LeagueParams{})
	path := fmt.Sprintf("/api/v1/leagues/%s/seasons/%s/matches/%s", other.ID, f.season.ID, m.ID)

	requests := []struct {
		method string
		path   string
		body   string
	}{
		{http.MethodGet, path, ""},
		{http.MethodPatch, path, `{"matchday": 2}`},
		{http.MethodDelete, path, ""},
		{http.MethodPost, path + "/start", ""},
		{http.MethodPost, path + "/cancel", ""},
	}
	for _, rq := range requests {
		if rec := testhttp.Do(t, f.router, rq.method, rq.path, rq.body); rec.Code != http.StatusNotFound {
			t.Errorf("%s %s: status = %d, want %d: the season belongs to another league", rq.method, rq.path, rec.Code, http.StatusNotFound)
		}
	}

	listPath := fmt.Sprintf("/api/v1/leagues/%s/seasons/%s/matches", other.ID, f.season.ID)
	if matches := decode[[]matchResponse](t, testhttp.Do(t, f.router, http.MethodGet, listPath, "")); len(matches) != 0 {
		t.Errorf("list from another league has %d matches, want 0", len(matches))
	}
}

func TestMatchLifecycle(t *testing.T) {
	f := newFixture(t)
	m := f.schedule(t, f.home, f.away, 1)

	started := f.do(t, http.MethodPost, f.matchPath(m.ID, "/start"), "", http.StatusOK)
	if started.Status != StatusLive || started.HomeScore == nil || *started.HomeScore != 0 || *started.AwayScore != 0 {
		t.Errorf("after start: match = %+v, want live at 0-0", started)
	}

	scored := f.do(t, http.MethodPut, f.matchPath(m.ID, "/score"), `{"home": 2, "away": 1}`, http.StatusOK)
	if *scored.HomeScore != 2 || *scored.AwayScore != 1 {
		t.Errorf("after score: %d-%d, want 2-1", *scored.HomeScore, *scored.AwayScore)
	}

	finished := f.do(t, http.MethodPost, f.matchPath(m.ID, "/finish"), "", http.StatusOK)
	if finished.Status != StatusFinished || *finished.HomeScore != 2 || *finished.AwayScore != 1 {
		t.Errorf("after finish: match = %+v, want finished at 2-1", finished)
	}

	got := f.do(t, http.MethodGet, f.matchPath(m.ID, ""), "", http.StatusOK)
	if got.Status != StatusFinished {
		t.Errorf("stored status = %s, want %s", got.Status, StatusFinished)
	}
}

func TestMatch_ForbiddenTransitions(t *testing.T) {
	tests := []struct {
		name    string
		prepare func(f fixture, id uuid.UUID)
		method  string
		action  string
		body    string
	}{
		{"finish a scheduled match", func(fixture, uuid.UUID) {}, http.MethodPost, "/finish", ""},
		{"score a scheduled match", func(fixture, uuid.UUID) {}, http.MethodPut, "/score", `{"home": 1, "away": 0}`},
		{"start a match twice", func(f fixture, id uuid.UUID) {
			f.do(t, http.MethodPost, f.matchPath(id, "/start"), "", http.StatusOK)
		}, http.MethodPost, "/start", ""},
		{"cancel a live match", func(f fixture, id uuid.UUID) {
			f.do(t, http.MethodPost, f.matchPath(id, "/start"), "", http.StatusOK)
		}, http.MethodPost, "/cancel", ""},
		{"postpone a live match", func(f fixture, id uuid.UUID) {
			f.do(t, http.MethodPost, f.matchPath(id, "/start"), "", http.StatusOK)
		}, http.MethodPost, "/postpone", `{}`},
		{"start a cancelled match", func(f fixture, id uuid.UUID) {
			f.do(t, http.MethodPost, f.matchPath(id, "/cancel"), "", http.StatusOK)
		}, http.MethodPost, "/start", ""},
		{"reschedule a cancelled match", func(f fixture, id uuid.UUID) {
			f.do(t, http.MethodPost, f.matchPath(id, "/cancel"), "", http.StatusOK)
		}, http.MethodPatch, "", `{"matchday": 2}`},
		{"delete a live match", func(f fixture, id uuid.UUID) {
			f.do(t, http.MethodPost, f.matchPath(id, "/start"), "", http.StatusOK)
		}, http.MethodDelete, "", ""},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			f := newFixture(t)
			m := f.schedule(t, f.home, f.away, 1)
			tt.prepare(f, m.ID)

			rec := testhttp.Do(t, f.router, tt.method, f.matchPath(m.ID, tt.action), tt.body)
			if rec.Code != http.StatusConflict {
				t.Errorf("status = %d, want %d, body = %s", rec.Code, http.StatusConflict, rec.Body)
			}
		})
	}
}

