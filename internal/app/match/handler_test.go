type fixture struct {
	router       http.Handler
	seed         *testdb.Seeder
	season       db.Season
	home, away   db.Team
	third        db.Team
	unregistered db.Team
}

func newFixture(t *testing.T) fixture {
	t.Helper()
	s := testdb.New(t, testPool)
	store := NewPostgresStore(testPool)

	r := chi.NewRouter()
	r.Mount("/api/v1/leagues/{leagueID}/seasons/{seasonID}/matches", NewHandler(NewService(store), store).Routes())

	f := fixture{
		router:       r,
		seed:         s,
		season:       s.CreateSeason(testdb.SeasonParams{}),
		home:         s.CreateTeam(testdb.TeamParams{}),
		away:         s.CreateTeam(testdb.TeamParams{}),
		third:        s.CreateTeam(testdb.TeamParams{}),
		unregistered: s.CreateTeam(testdb.TeamParams{}),
	}
	s.RegisterTeams(f.season, f.home, f.away, f.third)
	return f
}

func (f fixture) matchesPath() string {
	return fmt.Sprintf("/api/v1/leagues/%s/seasons/%s/matches", f.season.LeagueID, f.season.ID)
}

func (f fixture) matchPath(id uuid.UUID, action string) string {
	return fmt.Sprintf("%s/%s%s", f.matchesPath(), id, action)
}

func scheduleBody(home, away uuid.UUID, matchday int, kickoffAt string) string {
	if kickoffAt == "" {
		return fmt.Sprintf(`{"home_team_id": %q, "away_team_id": %q, "matchday": %d}`, home, away, matchday)
	}
	return fmt.Sprintf(`{"home_team_id": %q, "away_team_id": %q, "matchday": %d, "kickoff_at": %q}`, home, away, matchday, kickoffAt)
}

func decode[T any](t *testing.T, rec *httptest.ResponseRecorder) T {
	t.Helper()
	var v T
	if err := json.NewDecoder(rec.Body).Decode(&v); err != nil {
		t.Fatalf("decode response: %v", err)
	}
	return v
}

func (f fixture) do(t *testing.T, method, path, body string, wantStatus int) matchResponse {
	t.Helper()
	rec := testhttp.Do(t, f.router, method, path, body)
	if rec.Code != wantStatus {
		t.Fatalf("%s %s: status = %d, want %d, body = %s", method, path, rec.Code, wantStatus, rec.Body)
	}
	return decode[matchResponse](t, rec)
}

func (f fixture) schedule(t *testing.T, home, away db.Team, matchday int) matchResponse {
	t.Helper()
	return f.do(t, http.MethodPost, f.matchesPath(), scheduleBody(home.ID, away.ID, matchday, "2025-10-04T18:00:00Z"), http.StatusCreated)
}

func TestScheduleThenGetMatch(t *testing.T) {
	f := newFixture(t)

	created := f.schedule(t, f.home, f.away, 1)
	switch {
	case created.ID == uuid.Nil:
		t.Error("id is empty, want the id generated by the database")
	case created.Status != StatusScheduled || created.HomeScore != nil || created.AwayScore != nil:
		t.Errorf("match = %+v, want it scheduled without a score", created)
	case created.HomeTeamID != f.home.ID || created.AwayTeamID != f.away.ID || created.Matchday != 1:
		t.Errorf("match = %+v, want home vs away on matchday 1", created)
	case created.KickoffAt == nil:
		t.Error("kickoff_at is empty, want the kickoff sent")
	}

	got := f.do(t, http.MethodGet, f.matchPath(created.ID, ""), "", http.StatusOK)
	if got.ID != created.ID || got.Status != StatusScheduled {
		t.Errorf("get = %+v, want the created match", got)
	}
}

