func newTestRouter() http.Handler {
	r := chi.NewRouter()
	r.Mount("/api/v1/leagues/{leagueID}/teams", NewHandler(NewPostgresStore(testPool)).Routes())
	return r
}

func teamsPath(l db.League) string {
	return fmt.Sprintf("/api/v1/leagues/%s/teams", l.ID)
}

func TestCreateThenGetTeam(t *testing.T) {
	league := testdb.New(t, testPool).CreateLeague(testdb.LeagueParams{})
	router := newTestRouter()

	rec := testhttp.Do(t, router, http.MethodPost, teamsPath(league),
		`{"name": "Marseille", "logo": "https://example.com/om.png"}`)
	if rec.Code != http.StatusCreated {
		t.Fatalf("create: status = %d, want %d, body = %s", rec.Code, http.StatusCreated, rec.Body)
	}

	var created teamResponse
	if err := json.NewDecoder(rec.Body).Decode(&created); err != nil {
		t.Fatalf("decode create response: %v", err)
	}
	if created.ID == uuid.Nil {
		t.Fatal("create: id is 0, want the id generated by the database")
	}
	if created.LeagueID != league.ID {
		t.Errorf("create: league_id = %s, want %s (from the URL)", created.LeagueID, league.ID)
	}

	rec = testhttp.Do(t, router, http.MethodGet, fmt.Sprintf("%s/%s", teamsPath(league), created.ID), "")
	if rec.Code != http.StatusOK {
		t.Fatalf("get: status = %d, want %d, body = %s", rec.Code, http.StatusOK, rec.Body)
	}

	var got teamResponse
	if err := json.NewDecoder(rec.Body).Decode(&got); err != nil {
		t.Fatalf("decode get response: %v", err)
	}
	if got.Name != "Marseille" || got.Logo == nil || *got.Logo != "https://example.com/om.png" {
		t.Errorf("get: got %+v, want name Marseille with its logo", got)
	}
}

