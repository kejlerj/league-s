		t.Run(tt.name, func(t *testing.T) {
			s := testdb.New(t, testPool)
			f := fixture{league: s.CreateLeague(testdb.LeagueParams{}), other: s.CreateLeague(testdb.LeagueParams{})}
			f.team = s.CreateTeam(testdb.TeamParams{League: &f.league})

			rec := testhttp.Do(t, newTestRouter(), http.MethodGet, tt.path(f), "")
			if rec.Code != tt.wantStatus {
				t.Errorf("status = %d, want %d, body = %s", rec.Code, tt.wantStatus, rec.Body)
			}
		})
