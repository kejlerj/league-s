func TestListTeams(t *testing.T) {
	s := testdb.New(t, testPool)
	league := s.CreateLeague(testdb.LeagueParams{})
	other := s.CreateLeague(testdb.LeagueParams{})
	s.CreateTeam(testdb.TeamParams{League: &league, Name: "Lyon"})
	s.CreateTeam(testdb.TeamParams{League: &league, Name: "Lens"})
	s.CreateTeam(testdb.TeamParams{League: &other, Name: "Nantes"})

	rec := testhttp.Do(t, newTestRouter(), http.MethodGet, teamsPath(league), "")
	if rec.Code != http.StatusOK {
		t.Fatalf("status = %d, want %d, body = %s", rec.Code, http.StatusOK, rec.Body)
	}

	var got []teamResponse
	if err := json.NewDecoder(rec.Body).Decode(&got); err != nil {
		t.Fatalf("decode response: %v, body = %s", err, rec.Body)
	}

	var names []string
	for _, team := range got {
		names = append(names, team.Name)
		if team.LeagueID != league.ID {
			t.Errorf("team %q has league_id %s, want %s", team.Name, team.LeagueID, league.ID)
		}
	}
	if !slices.Equal(names, []string{"Lens", "Lyon"}) {
		t.Errorf("teams = %v, want [Lens Lyon]: teams of the league only, sorted by name", names)
	}
}

